"""Turns the Dialogue crew's validated handoffs into files for the Godot project and the creator.

Outputs (in the chosen output folder):
  dialogue_opening.json         game data loaded by LightingTheStorm/scripts/dialogue/dialogue_loader.gd
  DIALOGUE_OPENING.md           review list for the creator (voice and lore approval before recording)
  handoffs/01..03_*.json        each agent's validated handoff (traceability)
  run_log.json                  every guardrail attempt: which agent, what the checks caught
  HANDOFF.md, REPORT.md         notes in the AI Agent Strategy's fixed format

Nothing is written as game data unless every contract check passes again end to end.
"""
import json
from datetime import datetime, timezone
from pathlib import Path

from validators import check_dialogue, check_dialogue_brief, check_review

SPEAKER_META = {
    "TED": {"name": "Ted", "colour": "#1F2A44", "role": "Lighthouse master (boss)"},
    "JEFF": {"name": "Jeff", "colour": "#2F4A34", "role": "Sailor, guides the crossing"},
    "DANIEL": {"name": "Daniel", "colour": "#7A2620", "role": "Young sailor, shelters in the basement"},
}

ASSUMPTIONS = [
    "Lore vs GDD: WORLD.md puts the ship reveal before the crossing; the GDD (1 Oct 2026) puts it at the boarding threshold. The brief follows the GDD.",
    "Lore says 'lamp head'; the GDD says 'burner'. Dialogue uses 'burner'.",
    "The engine room is assumed to be the basement (Daniel's shelter). Level Layout should confirm.",
    "Decided by the creator: the player is 'the new guy'; Ted's position in steps 2-3 is fine as written.",
    "Existing offline Jeff return-crossing lines (offline_llm.py) still say 'lad'; the dialogue checks would reject that for the player.",
    "Step 1 is the only repair covered. The GDD's second Gate 1 repair is not part of this task.",
]


def final_checks(state: dict) -> list[str]:
    """Re-run every contract check end to end before writing game data."""
    missing = [k for k in ("dialogue_brief", "dialogue", "dialogue_review") if k not in state]
    if missing:
        return [f"Pipeline incomplete, missing handoffs: {missing}"]
    b, d, r = state["dialogue_brief"], state["dialogue"], state["dialogue_review"]
    return check_dialogue_brief(b) + check_dialogue(d, b) + check_review(r)


def build_game_data(state: dict, mode: str) -> dict:
    b, d, r = state["dialogue_brief"], state["dialogue"], state["dialogue_review"]
    attempts = [e for e in state.get("log", []) if e["task"] == "OPENING_DIALOGUE_WRITE"]
    rounds = len(state.get("history", []))
    revisions = [e for e in state.get("log", []) if e["task"].startswith("OPENING_DIALOGUE_REVISE_")]
    return {
        # A REVISE verdict means the reviewer found problems: never let that data look approved.
        "status": "proposed" if r.verdict == "PASS" else "needs_revision",
        "reviewer_issues": r.issues,
        "game": "Lighting the Storm",
        "slice": b.slice,
        "notes": "Creator approves voice and lore before recording (AI Agent Strategy, Dialogue agent).",
        "generated_by": {
            "pipeline": "storm_crew / dialogue_crew.py",
            "mode": mode,
            "agents": ["Production Orchestrator", "Dialogue agent", "Canon and Review Orchestrator"],
            "dialogue_attempts": len(attempts),
            "revision_rounds": rounds,
            "revision_attempts": len(revisions),
            "review_verdict": r.verdict,
            "generated_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        },
        "speakers": {k: SPEAKER_META[k] for k in b.speakers},
        "steps": [s.model_dump() for s in b.steps],
        "events": [{"event_id": e.event_id, "step": e.step, "emitted_by": "game", "note": e.note,
                    "existing_crew_event": e.existing_crew_event} for e in b.events],
        "lines": [ln.model_dump(exclude_none=True) for ln in d.lines],
        "journal": [j.model_dump() for j in d.journal],
    }


def review_list(data: dict, decisions: list[str]) -> str:
    out = ["# Opening Dialogue: Steps 1-3 (Gate 1 slice)", "",
           f"Status: **{data['status']}**. Generated by the Opening Dialogue Crew ({data['generated_by']['mode']} mode; "
           f"{data['generated_by']['dialogue_attempts']} Dialogue-agent attempt(s), verdict "
           f"{data['generated_by']['review_verdict']}). The creator approves voice and lore before anything is recorded.", "",
           "**Voice rules used:** Ted is gruff, snarky and old-school, calls city folk \"new money toffs\", and grunts "
           "and coughs. Jeff is wry, wiry and frantic under pressure. Daniel is light-hearted and anxious. The player, "
           "called the new guy, never speaks. Nothing mentions a timer, shows a marker or confirms a supernatural cause.", "",
           "Lines reusing a canon sample line say so in their delivery note. **Pick one** means the game plays one "
           "option at random.", ""]
    by_step: dict[int, list] = {}
    for ln in data["lines"]:
        by_step.setdefault(ln["step"], []).append(ln)
    steps = data["steps"] + [{"step": 0, "title": "Optional discoveries", "location": "Lighthouse and basement",
                              "player_action": "Unprompted reactions to the haunted-lighthouse details (Pillar 1)."}]
    for st in steps:
        label = f"Step {st['step']}: {st['title']}" if st["step"] else st["title"]
        out += [f"## {label}", "", f"*Location:* {st['location']}  ", f"*Player does:* {st['player_action']}", ""]
        order = []
        for ln in by_step.get(st["step"], []):
            if ln["trigger"] not in order:
                order.append(ln["trigger"])
        for trig in order:
            ev = next(e for e in data["events"] if e["event_id"] == trig)
            out += [f"### On `{trig}`", f"*{ev['note']}*", ""]
            seen_groups: set[str] = set()
            for ln in (x for x in by_step[st["step"]] if x["trigger"] == trig):
                tag = f"nudge tier {ln['tier']}" if ln["kind"] == "nudge" else ln["kind"]
                ind = "  " if ln.get("group") else ""
                if ln.get("group") and ln["group"] not in seen_groups:
                    seen_groups.add(ln["group"])
                    out.append("- **Pick one:**")
                out.append(f"{ind}- **{ln['speaker']}** `{ln['line_id']}` ({tag}): \"{ln['text']}\"  ")
                out.append(f"{ind}  *delivery: {ln['delivery']}*")
                for key, lab in (("assist_text", "assist hint"), ("staging", "staging"), ("note", "note")):
                    if ln.get(key):
                        out.append(f"{ind}  *{lab}:* {ln[key]}")
            out.append("")
    out += ["## Objective journal (handwritten, the new guy's own words)", "",
            "| ID | Step | Written on | Entry |", "|---|---|---|---|"]
    out += [f"| `{j['journal_id']}` | {j['step']} | `{j['trigger']}` | {j['text']} |" for j in data["journal"]]
    out += ["", "## Open creator decisions", ""] + [f"{i}. {q}" for i, q in enumerate(decisions, 1)]
    out += ["", "## Assumptions to confirm", ""] + [f"{i}. {q}" for i, q in enumerate(ASSUMPTIONS, 1)]
    counts = {k: sum(1 for ln in data["lines"] if ln["speaker"] == k) for k in data["speakers"]}
    out += ["", f"*{len(data['lines'])} lines: " + ", ".join(f"{SPEAKER_META[k]['name']} {n}" for k, n in counts.items()) + ".*", ""]
    return "\n".join(out)


def write_outputs(state: dict, out_dir: str, mode: str) -> tuple[Path, list[str]]:
    out = Path(out_dir)
    (out / "handoffs").mkdir(parents=True, exist_ok=True)
    problems = final_checks(state)
    (out / "run_log.json").write_text(json.dumps(state.get("log", []), indent=2), encoding="utf-8")
    for h in state.get("history", []):
        (out / "handoffs" / f"history_round{h['round']}_dialogue.json").write_text(h["dialogue"].model_dump_json(indent=2), encoding="utf-8")
        (out / "handoffs" / f"history_round{h['round']}_review.json").write_text(h["review"].model_dump_json(indent=2), encoding="utf-8")
    for i, key in enumerate(("dialogue_brief", "dialogue", "dialogue_review"), 1):
        if key in state:
            (out / "handoffs" / f"0{i}_{key}.json").write_text(state[key].model_dump_json(indent=2), encoding="utf-8")

    if problems:
        (out / "REPORT.md").write_text("# REPORT\n\nPipeline blocked:\n" + "\n".join(f"- {p}" for p in problems),
                                       encoding="utf-8")
        return out, problems

    data = build_game_data(state, mode)
    r = state["dialogue_review"]
    (out / "dialogue_opening.json").write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (out / "DIALOGUE_OPENING.md").write_text(review_list(data, r.open_creator_decisions), encoding="utf-8")
    checks = "\n".join(f"- [{c.result.upper()}] {c.check}: {c.evidence}" for c in r.pillar_checks + r.decisions_log_checks)
    decisions = "\n".join(f"- {d}" for d in r.open_creator_decisions) or "- None"
    caught = [e for e in state.get("log", []) if not e["passed"]]
    caught_txt = "\n".join(f"- {e['agent']} (attempt {e['attempt']}): {len(e['errors'])} error(s)" for e in caught) or "- None"
    (out / "HANDOFF.md").write_text(f"""# HANDOFF - GATE1_OPENING_DIALOGUE

## 1. Task and goal
Write the Gate 1 opening dialogue (steps 1-3) for Ted, Jeff and Daniel as game data with stable IDs.

## 2. Files changed
- `dialogue_opening.json` (game data), `DIALOGUE_OPENING.md` (review list)
- `handoffs/01_dialogue_brief.json`, `02_dialogue.json`, `03_dialogue_review.json`, `run_log.json`

## 3. How to run and test
- Godot 4: copy `dialogue_opening.json` to `res://data/dialogue/` and use `scripts/dialogue/dialogue_loader.gd`.
- Regenerate: `python main_dialogue.py {'--offline ' if mode == 'offline' else ''}--out dialogue_output`

## 4. Observed behaviour
{r.handoff_summary}
Run mode: {mode}. Guardrail feedback during the run:
{caught_txt}

{checks}

## 5. Not verified
- Voice performance and lore approval (creator).
- The loader script has not been run in the Godot engine.

## 6. Licences and provenance
Text generated by the Opening Dialogue Crew from the GDD and Lore Build canon; no external assets.

## 7. Interface or contract changes proposed
New event IDs (see `events` in the JSON). The existing event RETURN_DEPARTED is the hand-off to JEFF_RET_*.

## 8. Open creator decisions
{decisions}
""", encoding="utf-8")
    (out / "REPORT.md").write_text(f"""# REPORT - GATE1_OPENING_DIALOGUE

**What was delegated:** brief (Production Orchestrator), dialogue (Dialogue agent), canon review (Canon and Review Orchestrator).

**What came back:** {len(data['lines'])} lines, {len(data['journal'])} journal entries, review verdict {r.verdict}.

**What passed review:** all {len(r.pillar_checks) + len(r.decisions_log_checks)} pillar and Decisions-log checks; all deterministic contract checks.

**What failed and why:** {'; '.join(r.issues) or 'Nothing in the final output.'} Guardrail catches during the run:
{caught_txt}

**What remains:** creator approval of voice and lore before recording; engine test of the loader.

**Creator decisions that are blocking:**
{decisions}
""", encoding="utf-8")
    return out, []
