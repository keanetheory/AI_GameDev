"""Run the World Crew (Boat, Player Movement, Lighting + reviewer) for Lighting the Storm.

Examples:
  python main_world.py --offline                                   # no API key: scripted model, real agents and guardrails
  python main_world.py                                             # a real model writes the specs
  python main_world.py --offline --godot-dir ../LightingTheStorm   # also copies the JSON to data/world/
"""
import argparse
import json
import shutil
import sys
from datetime import datetime, timezone
from pathlib import Path

from style_guide import load_style_guide
from world_crew import build_world_crew
from world_validators import check_boat, check_lighting, check_player, check_world_review

FILES = {"boat": "boat_spec.json", "player": "player_movement_spec.json", "lighting": "lighting_spec.json"}


def final_checks(state: dict, guide) -> list[str]:
    missing = [k for k in ("boat", "player", "lighting", "review") if k not in state]
    if missing:
        return [f"Pipeline incomplete, missing handoffs: {missing}"]
    return (check_boat(state["boat"]) + check_player(state["player"])
            + check_lighting(state["lighting"], guide) + check_world_review(state["review"]))


def write_outputs(state: dict, out_dir: str, mode: str, guide) -> tuple[Path, list[str]]:
    out = Path(out_dir)
    (out / "handoffs").mkdir(parents=True, exist_ok=True)
    problems = final_checks(state, guide)
    for i, key in enumerate(("boat", "player", "lighting", "review"), 1):
        if key in state:
            (out / "handoffs" / f"0{i}_{key}.json").write_text(state[key].model_dump_json(indent=2), encoding="utf-8")
    if problems:
        (out / "REPORT.md").write_text("# REPORT\n\nPipeline blocked:\n" + "\n".join(f"- {p}" for p in problems),
                                       encoding="utf-8")
        return out, problems
    stamp = datetime.now(timezone.utc).isoformat(timespec="seconds")
    for key, name in FILES.items():
        data = {"generated_utc": stamp, **json.loads(state[key].model_dump_json())}
        (out / name).write_text(json.dumps(data, indent=2), encoding="utf-8")
    r = state["review"]
    flag = "--offline" if mode == "offline" else ""
    checks = "\n".join(f"- [{c.result.upper()}] {c.check}: {c.evidence}"
                       for c in r.pillar_checks + r.decisions_log_checks)
    decisions = "\n".join(f"- {d}" for d in r.open_creator_decisions) or "- None"
    (out / "HANDOFF.md").write_text(f"""# HANDOFF - WORLD SPECS (boat, player movement, lighting)

## 1. Task and goal
Specify the steam launch (dock <-> Saltgate port, fixed speed, A/D steering), smooth on-foot movement, and the lighting rig (supermoon, clouds, rain and lightning by phase, lighthouse lights, distant Saint Calder) for the first traversable Godot level.

## 2. Files changed
- `boat_spec.json`, `player_movement_spec.json`, `lighting_spec.json`
- `handoffs/01_boat.json` .. `04_review.json`

## 3. How to run and test
- Regenerate: `python main_world.py {flag}`
- Godot: the specs are data. Read them from the boat controller, `player.gd` and a lighting rig script (not written yet).

## 4. Observed behaviour
{r.handoff_summary}

{checks}

## 5. Not verified
- Nothing here has been played. Steering feel, walking feel, flash safety and hazard readability need creator playtesting.
- The Tide / Wave agent is not built; `waves_enabled` is false.

## 6. Licences and provenance
Data generated by the World Crew ({mode} mode); no external assets. Colours come from the locked style guide.

## 7. Interface or contract changes proposed
Adds a Player Movement agent to the roster (the design submission has ten workers).

## 8. Open creator decisions
{decisions}
""", encoding="utf-8")
    (out / "REPORT.md").write_text(f"""# REPORT - WORLD SPECS

**What was delegated:** boat spec (Boat / Physics agent), player movement spec (Player Movement agent), lighting spec (Lighting agent), canon review (Canon and Review Orchestrator).

**What passed review:** {len(r.pillar_checks) + len(r.decisions_log_checks)} pillar and Decisions-log checks, plus every deterministic check.

**What failed and why:** {'; '.join(r.issues) or 'Nothing in the final output (guardrail retries are in the console log).'}

**What remains:** build the Tide / Wave agent after the traversable Godot level exists; playtest; creator decisions below.

**Creator decisions that are blocking:**
{decisions}
""", encoding="utf-8")
    return out, []


def main() -> int:
    ap = argparse.ArgumentParser(description="World Crew - Lighting the Storm")
    ap.add_argument("--offline", action="store_true", help="use the scripted offline LLM (no API key)")
    ap.add_argument("--no-demo-errors", action="store_true", help="offline only: skip the deliberate first-attempt faults")
    ap.add_argument("--out", default="world_output")
    ap.add_argument("--godot-dir", help="Godot project folder; copies the JSON specs to data/world/")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args()
    try:
        from dotenv import load_dotenv
        load_dotenv()
    except ImportError:
        pass

    guide = load_style_guide()
    state: dict = {}
    if args.offline:
        from offline_world_llm import OfflineWorldLLM
        llm = OfflineWorldLLM(model="offline-scripted-world", inject_errors=not args.no_demo_errors)
        llm.state = state
    else:
        from llm_factory import make_real_llm
        llm = make_real_llm()
        if llm is None:
            return 2
    crew, state = build_world_crew(llm, guide, verbose=not args.quiet, state=state)
    try:
        crew.kickoff()
    except Exception as exc:
        print(f"\n[crew] stopped: {type(exc).__name__}: {exc}", file=sys.stderr)
    out, problems = write_outputs(state, args.out, "offline" if args.offline else "llm", guide)
    if problems:
        print("\n[crew] BLOCKED - specs not written:\n  " + "\n  ".join(problems))
        return 1
    if args.godot_dir:
        dest = Path(args.godot_dir) / "data" / "world"
        dest.mkdir(parents=True, exist_ok=True)
        for name in FILES.values():
            shutil.copy(out / name, dest / name)
        print(f"[crew] copied specs to {dest}")
    print(f"\n[crew] done. Specs in {out}  |  notes: HANDOFF.md, REPORT.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
