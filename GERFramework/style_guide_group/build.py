"""Regenerates STYLE_GUIDE.md and the three Claude Code agent definitions from style_guide.json and prompts/.

    python build.py
"""
from pathlib import Path

from sg_rules import GUIDE, HERE, render, rules_block

REPO = HERE.parent.parent
AGENTS = REPO / ".claude" / "agents"

DEFS = {
    "generator": ("ger-style-generator", "Style Generator Agent (Style Guide GER group, creator side). Writes the content it is asked for, "
                  "including deliberately off-brand test content, with no knowledge of the style guide. Output goes to the Style Evaluator.",
                  "Read"),
    "evaluator": ("ger-style-evaluator", "Style Evaluator Agent (Style Guide GER group, assessor side). Grades text 1-10 against the Lighting the "
                  "Storm style guide and returns SCORE: [X/10] and REASON: [...]. Never rewrites. Never pass/fail.",
                  "Read, Bash"),
    "refiner": ("ger-style-refiner", "Style Refiner Agent (Style Guide GER group). Takes the original text and the Evaluator's REASON and "
                "rewrites the text to score 10/10 on the Lighting the Storm style guide, with no human in between.",
                "Read"),
}


def style_guide_md() -> str:
    lines = [f"# Style Guide: {GUIDE['game']}", "",
             "Generated by `build.py` from `style_guide.json`. Every rule is pulled from the Lore Build, the final GDD "
             "(Executive Summary, AI Agent Strategy) or the project's `canon.py`; the source of each is cited.", "",
             f"**Scope:** {GUIDE['scope']}", "",
             f"**Record layout:** `{GUIDE['record_format']}`, at most {GUIDE['max_words_per_line']} words of text per line.", "",
             "## Voices", ""]
    lines += [f"- **{k}**: {v}" for k, v in GUIDE["speakers"].items()]
    for t in GUIDE["types"]:
        lines += ["", f"## {t}", "", "| ID | Weight | Rule | Checked by | Source |", "|---|---|---|---|---|"]
        for r in GUIDE["rules"]:
            if r["type"] == t:
                lines.append(f"| {r['id']} | {r['weight']} | {r['rule']} | {r['check']} | {r['source']} |")
    return "\n".join(lines) + "\n"


def agent_md(role: str) -> str:
    name, desc, tools = DEFS[role]
    return f"---\nname: {name}\ndescription: {desc}\ntools: {tools}\n---\n\n{render(role)}\n"


def main() -> None:
    (HERE / "STYLE_GUIDE.md").write_text(style_guide_md(), encoding="utf-8")
    AGENTS.mkdir(parents=True, exist_ok=True)
    for role in DEFS:
        (AGENTS / f"{DEFS[role][0]}.md").write_text(agent_md(role), encoding="utf-8")
    print("wrote STYLE_GUIDE.md and", ", ".join(f"{DEFS[r][0]}.md" for r in DEFS))


if __name__ == "__main__":
    main()
