"""Builds the per-character dialogue pages and the dialogue index from the crew's final output.

Source: Agent Crew/storm_crew/storm_crew/sample_output_live_revised/dialogue_opening.json
Writes: Docs/Lore Build/dialogue/characters/DIALOGUE_<NAME>.md, DIALOGUE_OPENING_FINAL.md, README.md
Run:    python tools/build_character_pages.py
"""
import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CREW = ROOT.parent / "Agent Crew" / "storm_crew" / "storm_crew"
SRC = CREW / "sample_output_live_revised"
DOCS = ROOT.parent / "Docs" / "Lore Build" / "dialogue"
LORE = ROOT.parent / "Docs" / "Lore Build" / "characters"
OUT = DOCS / "characters"
OUT.mkdir(parents=True, exist_ok=True)

data = json.loads((SRC / "dialogue_opening.json").read_text(encoding="utf-8"))
review = json.loads((SRC / "handoffs" / "03_dialogue_review.json").read_text(encoding="utf-8"))
gen = data["generated_by"]
STEP_TITLE = {s["step"]: f"Step {s['step']}: {s['title']}" for s in data["steps"]}
STEP_TITLE[0] = "Optional discoveries"
EV = {e["event_id"]: e["note"] for e in data["events"]}
CHAR = {"TED": ("Ted", "chr_ted"), "JEFF": ("Jeff", "chr_jeff"), "DANIEL": ("Daniel", "chr_daniel")}


def lore_voice(chr_id: str) -> list[str]:
    text = (LORE / f"{chr_id}.md").read_text(encoding="utf-8")
    m = re.search(r"^## Voice\n(.*?)(?=^## )", text, re.S | re.M)
    return [ln.rstrip() for ln in (m.group(1) if m else "").strip().splitlines() if ln.strip()]


def cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


for key, (name, chr_id) in CHAR.items():
    mine = [x for x in data["lines"] if x["speaker"] == key]
    kinds = {}
    for x in mine:
        kinds[x["kind"]] = kinds.get(x["kind"], 0) + 1
    groups = {x["group"] for x in mine if x.get("group")}
    out = [f"# {name}: Dialogue", "",
           f"Part of *Artifact #2: Character Dialogue Sequences*. [Opening dialogue (all characters)](../DIALOGUE_OPENING_FINAL.md) · "
           f"[Lore file](../../characters/{chr_id}.md) · "
           "[Data (crew output)](../../../../Agent%20Crew/storm_crew/storm_crew/sample_output_live_revised/dialogue_opening.json)", "",
           f"**Status:** `{data['status']}`. Written by the Opening Dialogue Crew with a live model ({gen['revision_rounds']} revision round(s)); "
           f"reviewer verdict **{review['verdict']}**. The creator approves voice and lore before anything is recorded.", "",
           "## Voice (from the lore file)", ""] + [f"> {ln}" for ln in lore_voice(chr_id)] + [
           "", "## At a glance", "",
           f"- **{len(mine)} lines** across {len({x['step'] for x in mine})} sections, {len(groups)} alternate groups (the game plays one option at random).",
           "- By kind: " + ", ".join(f"{k} {v}" for k, v in sorted(kinds.items())) + ".", ""]
    for step in sorted({x["step"] for x in mine}):
        out += [f"## {STEP_TITLE[step]}", "", "| ID | Plays on | Kind | Line | Delivery |", "|---|---|---|---|---|"]
        for x in (y for y in mine if y["step"] == step):
            tag = x["kind"] + (f" (tier {x['tier']})" if x.get("tier") else "") + (f" · alt `{x['group']}`" if x.get("group") else "")
            out.append(f"| `{x['line_id']}` | `{x['trigger']}` | {cell(tag)} | \"{cell(x['text'])}\" | {cell(x['delivery'])} |")
        out.append("")
    notes = [x for x in mine if x.get("staging") or x.get("note") or x.get("assist_text")]
    if notes:
        out += ["## Staging, hints and notes", ""]
        for x in notes:
            for lab, k in (("staging", "staging"), ("note", "note"), ("assist hint", "assist_text")):
                if x.get(k):
                    out.append(f"- `{x['line_id']}` *{lab}:* {x[k]}")
        out.append("")
    out += ["---", f"*Generated by `LightingTheStorm/tools/build_character_pages.py` from `dialogue_opening.json`. Do not edit by hand.*", ""]
    (OUT / f"DIALOGUE_{key}.md").write_text("\n".join(out), encoding="utf-8")

shutil.copy(SRC / "DIALOGUE_OPENING.md", DOCS / "DIALOGUE_OPENING_FINAL.md")

counts = {k: sum(1 for x in data["lines"] if x["speaker"] == k) for k in CHAR}
idx = ["# Character Dialogue Sequences", "",
       "Dialogue for the opening of *Lighting the Storm* (Gate 1, steps 1-3), written by the Opening Dialogue Crew in `Agent Crew/storm_crew`.", "",
       "## Characters", "", "| Character | Lines | Page |", "|---|---|---|"]
idx += [f"| {CHAR[k][0]} | {counts[k]} | [DIALOGUE_{k}.md](characters/DIALOGUE_{k}.md) |" for k in CHAR]
idx += ["", "## Opening dialogue (all characters, by step and event)", "",
        f"- [Final: after the revision round](DIALOGUE_OPENING_FINAL.md) · status `{data['status']}`, {len(data['lines'])} lines",
        "- [Iteration 1: live model, reviewer verdict REVISE](DIALOGUE_OPENING_LIVE.md)",
        "- [Offline draft: the scripted first version](DIALOGUE_OPENING.md)", "",
        "## Diagrams", "",
        "- [Pathway from prompt to game, with the revision round](illustration_pathway_crew_run_live.png)",
        "- [Pathway for the scripted offline run](illustration_pathway_crew_run_offline.png)",
        "- [Opening dialogue flow: the three steps](illustration_opening_dialogue_flow.png)", ""]
(DOCS / "README.md").write_text("\n".join(idx), encoding="utf-8")
print("wrote", [p.name for p in sorted(OUT.glob("*.md"))], "+ DIALOGUE_OPENING_FINAL.md + README.md")
