"""Builds the per-character dialogue pages and the dialogue index from the game's script.

Source: data/dialogue/dialogue_opening.json, the lines the game plays (the crew's creator-picked output of 2026-10-15/16, then
the T50/T52 humour pass and the creator's edits since). Until 2026-11-03 this read the crew's copy in
AIAgentCrew/sample_output_picked, which stopped being updated after the picks, so the pages fell behind the game.
Writes: Docs/Lore Build/dialogue/characters/DIALOGUE_<NAME>.md, DIALOGUE_OPENING_FINAL.md, README.md
Run:    python tools/build_character_pages.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CREW = ROOT.parent / "AIAgentCrew"
SRC = CREW / "sample_output_picked"
DOCS = ROOT.parent / "Docs" / "Lore Build" / "dialogue"
LORE = ROOT.parent / "Docs" / "Lore Build" / "characters"
OUT = DOCS / "characters"
OUT.mkdir(parents=True, exist_ok=True)

GAME_JSON = ROOT / "data" / "dialogue" / "dialogue_opening.json"
data = json.loads(GAME_JSON.read_text(encoding="utf-8"))
review = json.loads((SRC / "handoffs" / "03_dialogue_review.json").read_text(encoding="utf-8"))
gen = data["generated_by"]
STEP_TITLE = {s["step"]: f"Step {s['step']}: {s['title']}" for s in data["steps"]}
STEP_TITLE[0] = "Optional discoveries"
EV = {e["event_id"]: e["note"] for e in data["events"]}
CHAR = {"TED": ("Ted", "chr_ted"), "ARTHUR": ("Arthur", "chr_arthur"), "DANIEL": ("Daniel", "chr_daniel")}


def lore_voice(chr_id: str) -> list[str]:
    text = (LORE / f"{chr_id}.md").read_text(encoding="utf-8")
    m = re.search(r"^## Voice\n(.*?)(?=^## )", text, re.S | re.M)
    return [ln.rstrip() for ln in (m.group(1) if m else "").strip().splitlines() if ln.strip()]


def cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


for key, (name, chr_id) in CHAR.items():
    mine = [x for x in data["lines"] if x["speaker"] == key]
    kinds = {}
    for x in mine:
        kinds[x["kind"]] = kinds.get(x["kind"], 0) + 1
    groups = {x["group"] for x in mine if x.get("group")}
    out = [f"# {name}: Dialogue", "",
           f"Part of *Artifact #2: Character Dialogue Sequences*. [Opening dialogue (all characters)](../DIALOGUE_OPENING_FINAL.md) · "
           f"[Lore file](../../characters/{chr_id}.md) · "
           "[Data (the game's script)](../../../../LightingTheStorm/data/dialogue/dialogue_opening.json)", "",
           f"**Status:** `{data['status']}`. Written by the Opening Dialogue Crew with a live model ({gen['revision_rounds']} revision round(s)), "
           f"then the creator picked one line per 'pick one' group on 2026-10-15 (deterministic review verdict **{review['verdict']}**); "
           "since then the T50/T52 humour pass and the creator's edits. These are the lines the game plays and the voice clips were "
           "recorded from.", "",
           "## Voice (from the lore file)", ""] + [f"> {ln}" for ln in lore_voice(chr_id)] + [
           "", "## At a glance", "",
           f"- **{len(mine)} lines** across {len({x['step'] for x in mine})} sections, {len(groups)} alternate groups (the creator picked one line per group, so none remain).",
           "- By kind: " + ", ".join(f"{k} {v}" for k, v in sorted(kinds.items())) + ".", ""]
    for step in sorted({x["step"] for x in mine}):
        out += [f"## {STEP_TITLE[step]}", "", "| ID | Plays on | Kind | Line | Delivery |", "|---|---|---|---|---|"]
        for x in (y for y in mine if y["step"] == step):
            tag = x["kind"] + (f" (tier {x['tier']})" if x.get("tier") else "") + (f" · alt `{x['group']}`" if x.get("group") else "")
            out.append(f"| `{x['line_id']}` | `{x['trigger']}` | {cell(tag)} | \"{cell(x['text'])}\" | {cell(x['delivery'])} |")
        out.append("")
    notes = [x for x in mine if x.get("staging") or x.get("note") or x.get("assist_text")]
    if notes:
        out += ["## Staging, hints and notes", ""]
        for x in notes:
            for lab, k in (("staging", "staging"), ("note", "note"), ("assist hint", "assist_text")):
                if x.get(k):
                    out.append(f"- `{x['line_id']}` *{lab}:* {x[k]}")
        out.append("")
    out += ["---", f"*Generated by `LightingTheStorm/tools/build_character_pages.py` from `data/dialogue/dialogue_opening.json`. Do not edit by hand.*", ""]
    (OUT / f"DIALOGUE_{key}.md").write_text("\n".join(out), encoding="utf-8")


def opening_page() -> str:
    """Every line by step and by the event that plays it, in the game's order."""
    ev = {e["event_id"]: e for e in data["events"]}
    out = [f"# Opening Dialogue: Steps 1-{max(s['step'] for s in data['steps'])}", "",
           f"Status: `{data['status']}`. The game's script ([data](../../../LightingTheStorm/data/dialogue/dialogue_opening.json)): "
           "the Opening Dialogue Crew's creator-picked lines (2026-10-15/16), the T50/T52 humour pass and the creator's edits since. "
           "Character pages: " + ", ".join(f"[{n}](characters/DIALOGUE_{k}.md)" for k, (n, _c) in CHAR.items()) + ".", "",
           f"*{data['notes']}*", ""]
    steps = sorted(data["steps"], key=lambda s: s["step"]) + [{"step": 0, "title": "Optional discoveries"}]
    for st in steps:
        lines = [x for x in data["lines"] if x["step"] == st["step"]]
        if not lines:
            continue
        out += [f"## {STEP_TITLE[st['step']]}", ""]
        if st.get("location"):
            out += [f"*Location:* {st['location']}  ", f"*Player does:* {st.get('player_action', '')}", ""]
        order = []
        for x in lines:
            if x["trigger"] not in order:
                order.append(x["trigger"])
        for trig in order:
            out.append(f"### On `{trig}`")
            if trig in ev:
                out.append(f"*{ev[trig]['note']}*")
            out.append("")
            for x in (y for y in lines if y["trigger"] == trig):
                tag = x["kind"] + (f" tier {x['tier']}" if x.get("tier") else "")
                out.append(f"- **{x['speaker']}** `{x['line_id']}` ({tag}): \"{x['text']}\"  ")
                out.append(f"  *delivery: {x['delivery']}*")
                for lab, k in (("requires", "requires"), ("staging", "staging"), ("assist hint", "assist_text"), ("note", "note")):
                    if x.get(k):
                        out.append(f"  *{lab}:* {x[k]}")
            out.append("")
    out += ["## Objective journal (handwritten, Isaac's own words)", "", "| ID | Step | Written on | Entry |", "|---|---|---|---|"]
    out += [f"| `{j['journal_id']}` | {j['step']} | `{j['trigger']}` | {cell(j['text'])} |" for j in data["journal"]]
    out += ["", "---", "*Generated by `LightingTheStorm/tools/build_character_pages.py` from `data/dialogue/dialogue_opening.json`. Do not edit by hand.*", ""]
    return "\n".join(out)


(DOCS / "DIALOGUE_OPENING_FINAL.md").write_text(opening_page(), encoding="utf-8")

counts = {k: sum(1 for x in data["lines"] if x["speaker"] == k) for k in CHAR}
idx = ["# Character Dialogue Sequences", "",
       "Dialogue for *Lighting the Storm* (Gate 1), as the game plays it: written by the Opening Dialogue Crew in `AIAgentCrew`, picked line by line by the creator (see [the picks](DIALOGUE_OPENING_CREATOR_PICKS.md)), then the T50/T52 humour pass and the creator's edits.", "",
       "## Characters", "", "| Character | Lines | Page |", "|---|---|---|"]
idx += [f"| {CHAR[k][0]} | {counts[k]} | [DIALOGUE_{k}.md](characters/DIALOGUE_{k}.md) |" for k in CHAR]
idx += ["", "## Opening dialogue (all characters, by step and event)", "",
        f"- [Current: the game's script](DIALOGUE_OPENING_FINAL.md) · status `{data['status']}`, {len(data['lines'])} lines",
        "- [The creator's picks and what changed](DIALOGUE_OPENING_CREATOR_PICKS.md)",
        "- Archive, before the picks (56 lines): [live revised](archive/2026-10-15_before_creator_picks/DIALOGUE_OPENING_FINAL.md), "
        "[iteration 1, REVISE](archive/2026-10-15_before_creator_picks/DIALOGUE_OPENING_LIVE.md), "
        "[offline draft](archive/2026-10-15_before_creator_picks/DIALOGUE_OPENING.md), "
        "[old pages and diagrams](archive/2026-10-15_before_creator_picks/)", "",
        "## Diagrams", "",
        "- [Pathway from prompt to game, with the revision round](illustration_pathway_crew_run_live.png)",
        "- [Pathway for the scripted offline run](illustration_pathway_crew_run_offline.png)",
        "- [Opening dialogue flow: the three steps](illustration_opening_dialogue_flow.png)", ""]
(DOCS / "README.md").write_text("\n".join(idx), encoding="utf-8")
print("wrote", [p.name for p in sorted(OUT.glob("*.md"))], "+ DIALOGUE_OPENING_FINAL.md + README.md")
